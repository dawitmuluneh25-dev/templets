/**
 * Export renderers: plain text, standalone HTML, FHIR DiagnosticReport JSON,
 * and a dependency-free PDF writer (PDF 1.4, Helvetica, A4, multi-page).
 *
 * Every renderer works from the report's rendered text, not from the live DOM,
 * so an export is reproducible from the stored document alone.
 */

import { reportText } from './doc.js';

function stamp(d = new Date()) {
  return d.toISOString().replace('T', ' ').slice(0, 19) + 'Z';
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function exportHeader(report) {
  const lines = [
    report.templateName,
    `Modality: ${report.modality || '-'}`,
    report.study?.accession ? `Accession: ${report.study.accession}` : null,
    report.study?.demographics ? `Patient: ${report.study.demographics}` : null,
    `Status: ${report.state === 'signed' ? 'SIGNED' : 'DRAFT'}`,
    report.signedAt ? `Signed: ${stamp(new Date(report.signedAt))}` : null,
    `Template version: ${report.templateVersion} (${report.templateType})`,
    `Generated: ${stamp()}`,
  ].filter(Boolean);
  return lines.join('\n');
}

/* -------------------------------------------------------------------- text */

export function toText(report) {
  return `${exportHeader(report)}\n\n${'-'.repeat(72)}\n\n${reportText(report)}`;
}

/* -------------------------------------------------------------------- html */

export function toHTML(report) {
  const body = esc(reportText(report));
  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>${esc(report.templateName)} — radiology report</title>
<style>
  body { font: 15px/1.6 ui-sans-serif, system-ui, -apple-system, Segoe UI, Roboto, sans-serif;
         max-width: 74ch; margin: 40px auto; padding: 0 20px; color: #16202b; }
  header { border-bottom: 1px solid #d8dde5; padding-bottom: 12px; margin-bottom: 24px; }
  h1 { font-size: 1.3rem; margin: 0 0 6px; }
  .meta { font-size: .82rem; color: #5b6675; }
  pre { white-space: pre-wrap; font: inherit; margin: 0; }
  footer { margin-top: 32px; border-top: 1px solid #d8dde5; padding-top: 10px;
           font-size: .76rem; color: #6e7a8b; }
</style></head>
<body>
<header>
  <h1>${esc(report.templateName)}</h1>
  <div class="meta">${esc(exportHeader(report)).replace(/\n/g, ' · ')}</div>
</header>
<pre>${body}</pre>
<footer>Generated by AlemHealth Reporting (prototype). Rendered from template version ${report.templateVersion}.</footer>
</body></html>`;
}

/* -------------------------------------------------------------------- FHIR */

export function toFHIR(report) {
  const text = reportText(report);
  const impression = (report.sections.find((s) => s.heading.toUpperCase() === 'IMPRESSION') || {});
  return {
    resourceType: 'DiagnosticReport',
    id: report.id,
    status: report.state === 'signed' ? 'final' : 'preliminary',
    category: [
      {
        coding: [
          {
            system: 'http://terminology.hl7.org/CodeSystem/v2-0074',
            code: 'RAD',
            display: 'Radiology',
          },
        ],
      },
    ],
    code: {
      text: report.templateName,
      coding: [{ system: 'http://loinc.org', code: '18748-4', display: 'Diagnostic imaging study' }],
    },
    subject: { reference: `Patient/${report.study?.patientRef || 'unknown'}`, display: report.study?.demographics || undefined },
    effectiveDateTime: report.createdAt,
    issued: report.signedAt || report.updatedAt,
    conclusion: impression.heading ? text.split(impression.heading)[1]?.trim().slice(0, 2000) : undefined,
    presentedForm: [
      {
        contentType: 'text/plain',
        title: 'Radiology report',
        data: btoa(unescape(encodeURIComponent(text))),
      },
    ],
    extension: [
      {
        url: 'urn:alem:template-version',
        valueString: `${report.templateId}@${report.templateVersion}`,
      },
    ],
  };
}

/* --------------------------------------------------------------------- PDF */

/** Restricts to printable ASCII so string length === byte length (exact xref). */
function ascii(s) {
  return String(s)
    .replace(/[\u2018\u2019\u02BC]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/\u00B0/g, ' deg')
    .replace(/[\u00D7\u2715]/g, 'x')
    .replace(/\t/g, '    ')
    .replace(/[^\x20-\x7E\n]/g, '?');
}

function pdfEscape(s) {
  return s.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function wrapLine(text, width) {
  if (text.length <= width) return [text];
  const words = text.split(/(\s+)/);
  const out = [];
  let line = '';
  for (const w of words) {
    if ((line + w).length > width && line.trim()) {
      out.push(line.replace(/\s+$/, ''));
      line = w.replace(/^\s+/, '');
    } else {
      line += w;
    }
  }
  if (line.trim()) out.push(line.replace(/\s+$/, ''));
  return out.length ? out : [''];
}

/** Builds a lightweight line list: template section headings are bold. */
function toPdfLines(text) {
  const src = ascii(text).split('\n');
  const lines = [];
  const headingRe = /^([A-Z][A-Z0-9 \-/&(),.']{2,45}):?$/;
  for (const raw of src) {
    const isHeading = headingRe.test(raw.trim()) && raw.trim().length > 2;
    const wrapped = wrapLine(raw, isHeading ? 60 : 92);
    for (const w of wrapped) lines.push({ text: w, bold: isHeading });
  }
  return lines;
}

const PAGE_H = 842;
const PAGE_W = 595;
const MARGIN = 50;
const LEADING = 15;
const FIRST_BASELINE = 788;
const LINES_PER_PAGE = Math.floor((FIRST_BASELINE - MARGIN) / LEADING);

function contentStream(lines) {
  let s = 'BT\n';
  s += `1 0 0 1 ${MARGIN} ${FIRST_BASELINE} Tm\n`;
  s += `${LEADING} TL\n`;
  let font = null;
  for (const l of lines) {
    const want = l.bold ? '/F2' : '/F1';
    if (want !== font) {
      s += `${want} ${l.bold ? 10.5 : 10} Tf\n`;
      font = want;
    }
    s += `(${pdfEscape(l.text)}) Tj T*\n`;
  }
  s += 'ET';
  return s;
}

/**
 * Serialises a minimal but valid PDF.
 * Returns Uint8Array. Verifiable with verifyPDF().
 */
export function toPDF(report) {
  const text = toText(report);
  const lines = toPdfLines(text);
  const pages = [];
  for (let i = 0; i < lines.length; i += LINES_PER_PAGE) {
    pages.push(lines.slice(i, i + LINES_PER_PAGE));
  }
  if (!pages.length) pages.push([]);

  const objects = new Map();
  const kids = pages.map((_, i) => `${6 + i * 2} 0 R`).join(' ');
  objects.set(1, '<< /Type /Catalog /Pages 2 0 R >>');
  objects.set(2, `<< /Type /Pages /Kids [${kids}] /Count ${pages.length} >>`);
  objects.set(3, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  objects.set(4, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');

  pages.forEach((pageLines, i) => {
    const contentNo = 5 + i * 2;
    const pageNo = 6 + i * 2;
    objects.set(contentNo, { stream: contentStream(pageLines) });
    objects.set(pageNo, {
      dict: `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] ` +
        `/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentNo} 0 R >>`,
    });
  });

  let max = 0;
  for (const k of objects.keys()) max = Math.max(max, k);

  let out = '%PDF-1.4\n';
  const offsets = new Array(max + 1).fill(0);

  for (let i = 1; i <= max; i++) {
    const obj = objects.get(i);
    offsets[i] = out.length;
    if (obj && obj.stream !== undefined) {
      const s = obj.stream;
      out += `${i} 0 obj\n<< /Length ${s.length} >>\nstream\n${s}\nendstream\nendobj\n`;
    } else if (obj && obj.dict) {
      out += `${i} 0 obj\n${obj.dict}\nendobj\n`;
    } else {
      out += `${i} 0 obj\n${obj}\nendobj\n`;
    }
  }

  const xrefStart = out.length;
  out += `xref\n0 ${max + 1}\n`;
  out += '0000000000 65535 f \n';
  for (let i = 1; i <= max; i++) {
    out += String(offsets[i]).padStart(10, '0') + ' 00000 n \n';
  }
  out += `trailer\n<< /Size ${max + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

  const bytes = new Uint8Array(out.length);
  for (let i = 0; i < out.length; i++) bytes[i] = out.charCodeAt(i) & 0xff;
  return bytes;
}

/**
 * Structural check used by the test harness: every xref entry must point at
 * the matching "N 0 obj" header, startxref must point at "xref", and the file
 * must end with %%EOF.
 */
export function verifyPDF(bytes) {
  const s = Buffer.from(bytes).toString('latin1');
  const problems = [];

  if (!s.startsWith('%PDF-1.4')) problems.push('missing %PDF header');
  if (!s.trimEnd().endsWith('%%EOF')) problems.push('missing %%EOF');

  const startxref = /startxref\n(\d+)\n/.exec(s);
  if (!startxref) {
    problems.push('missing startxref');
    return problems;
  }
  const xrefPos = Number(startxref[1]);
  if (!s.startsWith('xref', xrefPos)) problems.push(`startxref ${xrefPos} does not point at an xref table`);

  const xrefBody = s.slice(xrefPos);
  const countMatch = /^xref\n0 (\d+)\n/.exec(xrefBody);
  if (!countMatch) {
    problems.push('malformed xref header');
    return problems;
  }
  const count = Number(countMatch[1]);
  const entries = xrefBody.slice(countMatch[0].length).split('\n');
  // entries[0] describes object 0 (the free-list head), so object i is entries[i].
  for (let i = 1; i < count; i++) {
    const m = /^(\d{10}) 00000 n $/.exec(entries[i] || '');
    if (!m) {
      problems.push(`xref entry ${i} malformed: ${JSON.stringify(entries[i])}`);
      continue;
    }
    const off = Number(m[1]);
    if (!s.startsWith(`${i} 0 obj`, off)) {
      problems.push(`object ${i} offset ${off} points at ${JSON.stringify(s.slice(off, off + 12))}`);
    }
  }
  // Every stream's declared length must match the real byte span.
  const streamRe = /<< \/Length (\d+) >>\nstream\n/g;
  let m2;
  while ((m2 = streamRe.exec(s)) !== null) {
    const declared = Number(m2[1]);
    const start = m2.index + m2[0].length;
    const end = s.indexOf('\nendstream', start);
    if (end - start !== declared) problems.push(`stream length ${declared} != actual ${end - start}`);
  }
  return problems;
}

/* ---------------------------------------------------------------- download */

export function download(filename, data, mime) {
  const blob = data instanceof Uint8Array ? new Blob([data], { type: mime }) : new Blob([data], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export function safeFilename(report, ext) {
  const base = `${report.templateName}_${report.study?.accession || report.id}`
    .replace(/[^A-Za-z0-9._-]+/g, '-')
    .replace(/-+/g, '-')
    .slice(0, 80);
  return `${base}.${ext}`;
}
